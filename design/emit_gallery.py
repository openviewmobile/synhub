#!/usr/bin/env python3
"""把 design/gen/flutter/*.dart 变成工程内的"设计稿画廊"。

产物：
  lib/src/design/generated/*.dart   生成页面（import 改成 ../design_palette.dart）
  lib/src/design/design_gallery.dart 画廊 + 屏内切换（暗/亮 × 中/英）

画廊是**真机评审载体**：设计稿在真机上按 1:1 逻辑尺寸渲染，
评审时不用把 PNG 和人脑里的设备尺寸对起来。
"""
import glob
import json
import os
import re
import shutil

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(HERE, 'gen', 'flutter')
OUT = os.path.join(ROOT, 'lib', 'src', 'design')
GEN = os.path.join(OUT, 'generated')


def class_of(path):
    txt = open(path, encoding='utf-8').read()
    m = re.search(r'^class (\w+Page) extends StatelessWidget', txt, re.M)
    return m.group(1) if m else None


def main():
    os.makedirs(GEN, exist_ok=True)
    for old in glob.glob(os.path.join(GEN, '*.dart')):
        os.remove(old)

    entries = []
    for p in sorted(glob.glob(os.path.join(SRC, '*_page.dart'))):
        cls = class_of(p)
        if not cls:
            print('[skip] 没有公开 Page 类：', os.path.basename(p))
            continue
        sid = os.path.basename(p)[:-5]           # settings_page
        spec_path = os.path.join(HERE, 'spec', sid + '.json')
        title_zh, title_en = sid, sid
        if os.path.exists(spec_path):
            spec = json.load(open(spec_path, encoding='utf-8'))
            t = spec.get('title', sid)
            if isinstance(t, dict):
                title_zh, title_en = t.get('zh', sid), t.get('en', sid)
            else:
                title_zh = title_en = t
        txt = open(p, encoding='utf-8').read()
        txt = txt.replace("import 'design_palette.dart';",
                          "import '../design_palette.dart';")
        txt = txt.replace("import 'design_palette.dart'", "import '../design_palette.dart'")
        open(os.path.join(GEN, os.path.basename(p)), 'w', encoding='utf-8').write(txt)
        entries.append((sid, cls, title_zh, title_en))

    entries.sort(key=lambda e: e[0])
    imports = '\n'.join(
        f"import 'generated/{sid}.dart';" for sid, _, _, _ in entries)
    items = '\n'.join(
        f"  ScreenEntry('{sid}', '{zh} / {en}', () => const {cls}()),"
        for sid, cls, zh, en in entries)

    code = f'''// GENERATED by design/emit_gallery.py —— 设计稿画廊（{len(entries)} 屏）
import 'package:flutter/material.dart';

import 'design_palette.dart';
{imports}

class ScreenEntry {{
  const ScreenEntry(this.id, this.label, this.build);

  final String id;
  final String label;
  final Widget Function() build;
}}

final List<ScreenEntry> designScreens = <ScreenEntry>[
{items}
];

/// 画廊：所有设计稿按真机逻辑尺寸渲染，可逐屏切换 暗/亮 × 中/英。
class DesignGalleryPage extends StatefulWidget {{
  const DesignGalleryPage({{super.key}});

  @override
  State<DesignGalleryPage> createState() => _DesignGalleryPageState();
}}

class _DesignGalleryPageState extends State<DesignGalleryPage> {{
  bool _dark = true;

  @override
  Widget build(BuildContext context) {{
    return Scaffold(
      backgroundColor: _dark ? DesignPalette.dark.phone : DesignPalette.light.phone,
      appBar: AppBar(
        backgroundColor: _dark ? DesignPalette.dark.phone : DesignPalette.light.phone,
        foregroundColor: _dark ? DesignPalette.dark.text : DesignPalette.light.text,
        title: Text('设计稿 ${{designScreens.length}} 屏',
            style: TextStyle(
                color: _dark ? DesignPalette.dark.text : DesignPalette.light.text)),
        actions: <Widget>[
          IconButton(
            tooltip: _dark ? '切到亮色' : '切到暗色',
            icon: Icon(_dark ? Icons.light_mode_outlined : Icons.dark_mode_outlined),
            onPressed: () => setState(() => _dark = !_dark),
          ),
        ],
      ),
      body: GridView.builder(
        padding: const EdgeInsets.all(12),
        gridDelegate: const SliverGridDelegateWithFixedCrossAxisCount(
          crossAxisCount: 2,
          mainAxisSpacing: 10,
          crossAxisSpacing: 10,
          childAspectRatio: 0.62,
        ),
        itemCount: designScreens.length,
        itemBuilder: (BuildContext context, int i) {{
          final ScreenEntry e = designScreens[i];
          return GestureDetector(
            onTap: () => Navigator.of(context).push(MaterialPageRoute<void>(
              builder: (_) => _ScreenView(entry: e, dark: _dark),
            )),
            child: Container(
              decoration: BoxDecoration(
                color: _dark ? DesignPalette.dark.surface : DesignPalette.light.surface,
                borderRadius: BorderRadius.circular(12),
                border: Border.all(
                    color: _dark ? DesignPalette.dark.line : DesignPalette.light.line),
              ),
              clipBehavior: Clip.antiAlias,
              child: Column(
                children: <Widget>[
                  Expanded(
                    child: IgnorePointer(
                      child: FittedBox(
                        fit: BoxFit.contain,
                        alignment: Alignment.topCenter,
                        child: SizedBox(
                          width: 393,
                          height: 830,
                          child: Theme(
                            data: DesignTheme.of(
                                _dark ? DesignPalette.dark : DesignPalette.light,
                                _dark ? Brightness.dark : Brightness.light),
                            child: MediaQuery(
                              data: const MediaQueryData(
                                  size: Size(393, 830), devicePixelRatio: 3),
                              child: e.build(),
                            ),
                          ),
                        ),
                      ),
                    ),
                  ),
                  Padding(
                    padding: const EdgeInsets.fromLTRB(8, 4, 8, 8),
                    child: Text(e.label,
                        maxLines: 1,
                        overflow: TextOverflow.ellipsis,
                        style: TextStyle(
                            fontSize: 11,
                            color: _dark ? DesignPalette.dark.muted : DesignPalette.light.muted)),
                  ),
                ],
              ),
            ),
          );
        }},
      ),
    );
  }}
}}

class _ScreenView extends StatefulWidget {{
  const _ScreenView({{required this.entry, required this.dark}});

  final ScreenEntry entry;
  final bool dark;

  @override
  State<_ScreenView> createState() => _ScreenViewState();
}}

class _ScreenViewState extends State<_ScreenView> {{
  late bool _dark = widget.dark;
  bool _zh = true;

  @override
  Widget build(BuildContext context) {{
    final DesignPalette p = _dark ? DesignPalette.dark : DesignPalette.light;
    return Scaffold(
      backgroundColor: p.bg,
      appBar: AppBar(
        backgroundColor: p.phone,
        foregroundColor: p.text,
        title: Text(widget.entry.id,
            style: TextStyle(fontSize: 13, color: p.text)),
        actions: <Widget>[
          TextButton(
            onPressed: () => setState(() => _zh = !_zh),
            child: Text(_zh ? '中' : 'EN', style: TextStyle(color: p.accent)),
          ),
          IconButton(
            icon: Icon(_dark ? Icons.light_mode_outlined : Icons.dark_mode_outlined),
            onPressed: () => setState(() => _dark = !_dark),
          ),
        ],
      ),
      body: Theme(
        data: DesignTheme.of(p, _dark ? Brightness.dark : Brightness.light),
        child: MediaQuery(
          // 设计稿按 1.0 字号画；系统字体放大不许改变评审结论
          data: MediaQuery.of(context).copyWith(textScaler: TextScaler.noScaling),
          child: Localizations.override(
            context: context,
            locale: Locale(_zh ? 'zh' : 'en'),
            child: widget.entry.build(),
          ),
        ),
      ),
    );
  }}
}}
'''
    open(os.path.join(OUT, 'design_gallery.dart'), 'w', encoding='utf-8').write(code)
    print(f'[ok] 画廊 {len(entries)} 屏 → lib/src/design/design_gallery.dart')


if __name__ == '__main__':
    main()

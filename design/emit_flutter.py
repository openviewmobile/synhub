def _write_atomic(path: str, text: str) -> None:
    """先写 `.tmp` 再 `os.replace` —— 生成器崩了也不许留下 0 字节产物。"""
    assert isinstance(text, str) and len(text) > 500, '拒绝写入可疑的短内容'
    tmp = path + '.tmp'
    with open(tmp, 'w', encoding='utf-8') as fh:
        fh.write(text)
    os.replace(tmp, path)



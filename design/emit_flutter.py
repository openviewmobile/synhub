"""spec → Flutter 界面代码（**双主题 + 双语 + 6 种版式**）。

与 design/emit_svg.py 消费同一份 spec：
  * 颜色一律 `DesignPalette.of(context)`（暗/亮跟随系统）；
  * 文案一律本页 `_Strings`（zh/en 跟随系统语言）；
  * 版式：list / grid / player / detail / settings / unavailable。

用法：python3 design/emit_flutter.py design/spec/audio_song.json
"""

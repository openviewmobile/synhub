/// 取当前语言的文案；没有 delegate 时用中文实例顶上。
extension L10nBuildContextX on BuildContext {
  AppText get t => AppText.of(this) ?? AppTextZh();
}

/// 当前**应用语言**对应的文案表（语言开关变过就跟着变）。
///
/// 界面层用 `context.t`；`lib/src/core/**` 里少数拿不到 `context` 的地方用
/// [currentText]。**数据层不用它** —— `lib/src/dsm/**`、`lib/src/data/**`
/// 只认 `key + 中文原文`（`data_text.dart`），译文由 [setCurrentText] 注入。
AppText _current = AppTextZh();

/// 数据层/服务层用的当前文案表（`context` 拿不到时的入口）
AppText currentText() => _current;

/// 当前语言对应的**数据层译文表**（语言一变整表重建）。
Map<String, String> _dataTextTable = const {};

/// 语言变化时由 `SynologyChatApp` 写入（别在别处调；测试里也可用它模拟语言切换）。
///
/// 顺带把数据层的翻译器（`data_text.dart` 的 [setDataTextResolver]）装好：
/// `lib/src/dsm/**`、`lib/src/data/**` 要能被 `dart run tool/*.dart` 纯 Dart
/// 加载，**不能** import 本文件（`package:flutter` → `dart:ui`），所以译文
/// 只能从这里注入进去。没装翻译器时 `dataText` 回落中文原文。
void setCurrentText(AppText text) {
  _current = text;
  _dataTextTable = dataTextMap(text);
  setDataTextResolver((key, zh) => _dataTextTable[key] ?? zh);
}


// 多语言入口（生成代码在 `lib/l10n/gen/`，由 `flutter gen-l10n` 从 ARB 生成）。
//
// 约定：
//   * 只有**已经被翻译**的外壳文案才走 `context.t.xxx`；模块内部尚未翻译的
//     中文字面量保持原样，等该模块排期时再迁移（见 docs/app-identity-and-i18n.md）；
//   * 取不到本地化资源时**回落到中文**。离线 widget 测试大多只搭
//     `MaterialApp(home: …)`、不注入 delegate，有了这个回落它们照旧跑；
//   * 模板 ARB 是中文，所以"漏翻"只会退化成中文，不会冒出英文。


/// 用哨兵整数渲染一次带 **int 参数**的 getter，再把哨兵换成 `{name}` 占位符。
///
/// `chatSearchFromUsers(0)` 这类没法直接塞进 `Map<String, String>`：先渲染成
/// 一个绝不会出现在真实译文里的哨兵，再换回占位符。String 参数的 getter
/// 直接把 `'{name}'` 传进去就行，不用绕这一道。
const int _kTemplateInt = -987654321;
String _intTemplate(String rendered, String name) =>
    rendered.replaceFirst('$_kTemplateInt', '{$name}');

// ─────────────────────────────────────────────────────────────────────────
// ★★★ P0-1（Linux 站，第 109 轮）：**未知 / 不支持的 locale 必须回落，绝不许抛**
//
// 原始证据（`docs/platform-linux.md` §8.4 缺陷 1，像素
// `r108-linux-locale-C-redscreen.png`）：容器 / 最小 Linux 上 `LANG` 未设置
// ⇒ 平台 locale = `Locale('C')`（languageCode `c`），而 gen-l10n 生成的
// `lookupAppText()` 对 en/zh 之外的 locale **直接 `throw FlutterError`**。
// `SynologyChatApp.build` 里 `setCurrentText(lookupAppText(resolvedLocale))`
// 当场抛 ⇒ **整屏红屏**（不是"某个页面缺翻译"，是 App 第一屏就死）。
//
// 这不是仿真特有：任何 `LANG=C` / 未设 locale 的 Linux（CI、容器、最小发行版）
// 都会走到这里。**离线单测跑在 macOS 宿主上，永远碰不到这条路径** —— 所以
// 下面这组回落必须由 `test/locale_fallback_test.dart` 的**反向用例**钉住
// （raw `lookupAppText(Locale('c'))` 必须真抛，safe 版本必须不抛）。
// ─────────────────────────────────────────────────────────────────────────

/// 未知 locale 的回落目标。
///
/// 选 `en` 而不是 `zh`，理由只有一个：**必须与 Flutter 自己的兜底一致**。
/// `MaterialApp` 的 `supportedLocales` = `{AppText.supportedLocales, quill…}`，
/// 而 `basicLocaleListResolution` 在"一个都匹配不上"时返回
/// **`supportedLocales.first`** = `AppText.supportedLocales.first` = `en`。
/// 若这里回落 `zh`，界面层（delegate → en）会与数据层
/// （`setCurrentText` → zh）**串台**，出现中英混排（见 §2.0.13）。
const Locale kFallbackAppLocale = Locale('en');

/// locale 是否是我们真认识的语言（只按 `languageCode`，地区不参与）。
bool isSupportedAppLocale(Locale? locale) {
  final code = locale?.languageCode.toLowerCase();
  if (code == null || code.isEmpty) return false;
  return AppText.supportedLocales.any(
    (l) => l.languageCode.toLowerCase() == code,
  );
}

/// 把任意（含未知 / 为空）locale 归一成**受支持**的 locale。
///
/// * `zh` / `zh_Hant` / `en` / `en_US` → 原语言的规范形式；
/// * `C` / `POSIX` / `null` / `''` / 其它 → [kFallbackAppLocale]；
/// * **只回落，不抛** —— 这是 P0-1 的核心不变式。
Locale resolveAppLocale(Locale? locale) {
  final code = locale?.languageCode.toLowerCase();
  if (code != null && code.isNotEmpty) {
    for (final s in AppText.supportedLocales) {
      if (s.languageCode.toLowerCase() == code) return s;
    }
  }
  return kFallbackAppLocale;
}

/// [lookupAppText] 的**安全版**：未知 locale 回落，绝不抛。
///
/// 生成的 `lookupAppText()` 不能改（`flutter gen-l10n` 会覆盖），所以门面
/// 放在这里；**新代码一律用这个**。
AppText lookupAppTextSafe(Locale? locale) =>
    lookupAppText(resolveAppLocale(locale));

/// 平台语言。
///
/// 有 binding 时读 `WidgetsBinding.instance.platformDispatcher`（测试里
/// `localeTestValue` 改的就是它）；**没有** binding（纯 Dart 单元测试，
/// 例如 `system_message_test`）就退到引擎的 `PlatformDispatcher.instance`，
/// 免得为了取一个语言名把整个 binding 初始化起来。
Locale? platformLocale() {
  try {
    // 这个 getter 在 binding 没初始化时会抛（BindingBase.checkInstance）
    return WidgetsBinding.instance.platformDispatcher.locale;
  } on FlutterError {
    return PlatformDispatcher.instance.locale;
  }
}

/// 系统级文案（通知栏、后台服务、生物识别弹窗）用的应用名：跟随**平台语言**。
///
/// 这些地方拿不到 widget context（后台服务/通知/系统弹窗），也就不走
/// 应用内语言开关——跟系统语言走是最不容易出错的。
String platformAppName() => appNameIn(platformLocale());

/// 系统级文案表（通知栏、后台服务、生物识别弹窗）：跟随**平台语言**。
///
/// ★ P0-1：走 [lookupAppTextSafe] —— 之前这里对 `LANG=C` 的平台 locale 直接抛，
/// 通知/后台服务会跟着炸（与红屏同根因）。`null`（引擎都没起来）仍按老语义回落中文。
AppText platformText() =>
    lookupAppTextSafe(platformLocale() ?? const Locale('zh'));

/// 应用名（不依赖 delegate：桌面/任务切换器/通知都要用它）。
